/**
 * Subject vocabulary: Cambridge command words and key terms for each ALA subject.
 * Many students speak English well but have not learned what each command word asks them to do,
 * or the precise vocabulary each subject expects.
 * Command word definitions are Cambridge International's AS & A Level definitions.
 */

export interface CommandWord {
  word: string;
  definition: string;
  group: 'Recall' | 'Describe' | 'Explain' | 'Analyse' | 'Judge' | 'Apply';
  doThis: string;
  avoid: string;
}

