/**
 * Subjects at ALA and the benchmark each one is measured against.
 * Cambridge syllabus codes are Cambridge International AS & A Level codes.
 * "focus" describes what each readiness dimension means in the subject;
 * "support" is the matching faculty action when a student is weak on that dimension.
 */
import type { Dim } from '@/lib/dims';

export interface Subject {
  id: string;
  name: string;
  department: string;
  benchmark: {
    title: string;
    code?: string;
    level: string;
    summary: string;
    components: string[];
    expects: string[];
  };
  /** How much each dimension matters for overall readiness in this subject (0–3). */
  weights: Record<Dim, number>;
  /** What each dimension means in this subject (noun phrase). */
  focus: Record<Dim, string>;
  /** What faculty can do when students are weak on the dimension. */
  support: Record<Dim, string>;
  /** Adjustments that apply to every system for this subject, with the reason. */
  general?: { dims: Partial<Record<Dim, number>>; reason: string };
}

